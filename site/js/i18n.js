export const LANGS = { en, nl, de };
let current = 'en';

export function detectLang(list = (typeof navigator !== 'undefined' && navigator.languages) || []) {
  for (const tag of list) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (LANGS[base]) return base;
  }
  return 'en';
}

export function setLang(code) {
  current = LANGS[code] ? code : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const lang = () => current;

export function t(key, params = {}) {
  const v = LANGS[current][key] ?? en[key];
  if (v == null) return key;
  if (typeof v === 'function') return v(params);
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
}

export function formatDate(ts) {
  try {
    return new Intl.DateTimeFormat(current, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(ts));
  } catch {
    return new Date(ts).toLocaleString();
  }
}
